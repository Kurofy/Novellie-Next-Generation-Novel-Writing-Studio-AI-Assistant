import 'dart:io';
import 'package:dio/dio.dart';
import '../../domain/models/ai_models.dart';

class AiClientService {
  final Dio _dio;

  AiClientService([Dio? dio])
      : _dio = dio ??
            Dio(
              BaseOptions(
                connectTimeout: const Duration(seconds: 15),
                receiveTimeout: const Duration(seconds: 45),
                sendTimeout: const Duration(seconds: 15),
              ),
            );

  Future<String> sendMessage({
    required AiConfigModel config,
    required String prompt,
    String? novelContext,
  }) async {
    if (!config.isConfigured) {
      throw StateError('AI Assistant is not configured with an API key.');
    }

    final fullContext = StringBuffer();
    fullContext.writeln(
      'You are Novellie Assistant, an elite creative writing partner and novel editor.',
    );
    if (novelContext != null && novelContext.isNotEmpty) {
      fullContext.writeln('\n--- Current Novel Context ---');
      fullContext.writeln(novelContext);
      fullContext.writeln('-----------------------------\n');
    }

    switch (config.provider) {
      case AiProviderType.gemini:
        return _sendGemini(config, fullContext.toString(), prompt);
      case AiProviderType.anthropic:
        return _sendAnthropic(config, fullContext.toString(), prompt);
      case AiProviderType.openAi:
      case AiProviderType.custom:
        return _sendOpenAiCompatible(config, fullContext.toString(), prompt);
    }
  }

  Future<String> _sendGemini(
    AiConfigModel config,
    String systemInstructions,
    String userPrompt,
  ) async {
    // Ensure clean model name without models/ prefix or -latest suffix
    String rawModel = config.model.trim();
    if (rawModel.startsWith('models/')) {
      rawModel = rawModel.substring('models/'.length);
    }
    // Google Gemini API generateContent endpoints do NOT support '-latest' alias in v1beta / v1.
    // e.g. 'gemini-1.5-flash-latest' -> 'gemini-3.8-flash'
    if (rawModel.endsWith('-latest')) {
      rawModel = rawModel.substring(0, rawModel.length - '-latest'.length);
    }
    // Automatically migrate legacy or deprecated models to modern gemini-3.8-flash
    if (rawModel.isEmpty ||
        rawModel == 'gemini-1.5-flash' ||
        rawModel.contains('1.5-flash') ||
        rawModel == 'gemini-2.5-flash') {
      rawModel = 'gemini-3.8-flash';
    }

    Future<Response<Map<String, dynamic>>> callEndpoint(
      String modelName, {
      String apiVersion = 'v1beta',
    }) {
      final url =
          'https://generativelanguage.googleapis.com/$apiVersion/models/$modelName:generateContent?key=${config.apiKey}';
      return _dio.post<Map<String, dynamic>>(
        url,
        options: Options(headers: {'Content-Type': 'application/json'}),
        data: {
          'contents': [
            {
              'role': 'user',
              'parts': [
                {'text': '$systemInstructions\n\nUser Question:\n$userPrompt'},
              ],
            },
          ],
        },
      );
    }

    try {
      Response<Map<String, dynamic>> response;
      try {
        response = await callEndpoint(rawModel, apiVersion: 'v1beta');
      } on DioException catch (dioErr) {
        if (dioErr.response?.statusCode == 404) {
          // If 404 on v1beta, attempt calling v1 with the clean model name
          try {
            response = await callEndpoint(rawModel, apiVersion: 'v1');
          } catch (_) {
            // If still 404, try active alternate models in order: gemini-3.8-flash, gemini-3.5-flash, gemini-3.8-pro
            final alternateCandidates = [
              'gemini-3.8-flash',
              'gemini-3.5-flash',
              'gemini-3.8-pro',
            ].where((m) => m != rawModel).toList();

            Response<Map<String, dynamic>>? fallbackResp;
            for (final cand in alternateCandidates) {
              try {
                fallbackResp = await callEndpoint(cand, apiVersion: 'v1beta');
                break;
              } catch (_) {
                continue;
              }
            }

            if (fallbackResp != null) {
              response = fallbackResp;
            } else {
              rethrow;
            }
          }
        } else {
          rethrow;
        }
      }

      final data = response.data;
      if (data == null) throw Exception('Empty response received from Gemini API');

      final candidates = data['candidates'] as List<dynamic>?;
      if (candidates == null || candidates.isEmpty) {
        throw Exception('No response generated by Gemini');
      }

      final firstCandidate = candidates.first as Map<String, dynamic>;
      final content = firstCandidate['content'] as Map<String, dynamic>?;
      final parts = content?['parts'] as List<dynamic>?;
      final firstPart = parts?.first as Map<String, dynamic>?;
      final text = firstPart?['text'] as String?;

      return text ?? 'No response text received.';
    } catch (e, st) {
      _handleError(e, st, 'Google Gemini');
    }
  }

  Future<String> _sendAnthropic(
    AiConfigModel config,
    String systemInstructions,
    String userPrompt,
  ) async {
    final baseUrl = config.customBaseUrl?.isNotEmpty == true
        ? config.customBaseUrl!
        : 'https://api.anthropic.com/v1';

    try {
      final response = await _dio.post<Map<String, dynamic>>(
        '$baseUrl/messages',
        options: Options(
          headers: {
            'Content-Type': 'application/json',
            'x-api-key': config.apiKey,
            'anthropic-version': '2023-06-01',
          },
        ),
        data: {
          'model': config.model,
          'max_tokens': 4096,
          'system': systemInstructions,
          'messages': [
            {'role': 'user', 'content': userPrompt},
          ],
        },
      );

      final data = response.data;
      if (data == null) throw Exception('Empty response from Anthropic API');

      final content = data['content'] as List<dynamic>?;
      if (content == null || content.isEmpty) {
        throw Exception('No content returned by Anthropic');
      }

      final firstItem = content.first as Map<String, dynamic>;
      final text = firstItem['text'] as String?;

      return text ?? 'No response text received.';
    } catch (e, st) {
      _handleError(e, st, 'Anthropic Claude');
    }
  }

  Future<String> _sendOpenAiCompatible(
    AiConfigModel config,
    String systemInstructions,
    String userPrompt,
  ) async {
    final baseUrl = config.customBaseUrl?.isNotEmpty == true
        ? config.customBaseUrl!
        : 'https://api.openai.com/v1';

    try {
      final response = await _dio.post<Map<String, dynamic>>(
        '$baseUrl/chat/completions',
        options: Options(
          headers: {
            'Content-Type': 'application/json',
            'Authorization': 'Bearer ${config.apiKey}',
          },
        ),
        data: {
          'model': config.model,
          'messages': [
            {'role': 'system', 'content': systemInstructions},
            {'role': 'user', 'content': userPrompt},
          ],
        },
      );

      final data = response.data;
      if (data == null) throw Exception('Empty response from AI API');

      final choices = data['choices'] as List<dynamic>?;
      if (choices == null || choices.isEmpty) {
        throw Exception('No choices returned by API');
      }

      final firstChoice = choices.first as Map<String, dynamic>;
      final message = firstChoice['message'] as Map<String, dynamic>?;
      final text = message?['content'] as String?;

      return text ?? 'No response text received.';
    } catch (e, st) {
      _handleError(e, st, 'AI Service');
    }
  }

  Never _handleError(Object error, StackTrace stackTrace, String serviceName) {
    if (error is DioException) {
      if (error.type == DioExceptionType.connectionError) {
        final inner = error.error;
        final isHostLookupFailure = inner is SocketException ||
            (error.message != null &&
                (error.message!.contains('Failed host lookup') ||
                    error.message!.contains('SocketException') ||
                    error.message!.contains('errno = 7'))) ||
            (inner != null &&
                inner.toString().contains('Failed host lookup'));

        if (isHostLookupFailure) {
          throw Exception(
            'Network error: Failed to connect to $serviceName. Host address could not be resolved. '
            'Please verify your internet connection and network permissions.',
          );
        }

        throw Exception(
          'Network connection error: Failed to reach $serviceName. '
          'Please check your internet connection.',
        );
      }

      if (error.type == DioExceptionType.connectionTimeout ||
          error.type == DioExceptionType.sendTimeout ||
          error.type == DioExceptionType.receiveTimeout) {
        throw Exception(
          'Connection to $serviceName timed out. '
          'Please verify your network speed and try again.',
        );
      }

      if (error.type == DioExceptionType.badResponse) {
        final statusCode = error.response?.statusCode;
        final data = error.response?.data;
        String? apiMessage;

        if (data is Map<String, dynamic>) {
          final errField = data['error'];
          if (errField is Map<String, dynamic>) {
            apiMessage = errField['message']?.toString();
          } else if (errField is String) {
            apiMessage = errField;
          } else if (data['message'] is String) {
            apiMessage = data['message'] as String;
          }
        }

        if (statusCode == 400) {
          throw Exception(
            'Bad Request ($statusCode): ${apiMessage ?? "The request was rejected by $serviceName. Check model compatibility."}',
          );
        }

        if (statusCode == 401 || statusCode == 403) {
          throw Exception(
            'Authentication Error ($statusCode): Invalid or unauthorized API key. '
            '${apiMessage != null ? "Details: $apiMessage" : "Please check your configured API key in Settings."}',
          );
        }

        if (statusCode == 404) {
          throw Exception(
            'Gemini Error (404): ${apiMessage ?? "Model not found. Please verify you are using an active valid identifier such as gemini-3.8-flash or gemini-3.5-flash."}',
          );
        }

        if (statusCode == 429) {
          throw Exception(
            'Quota exceeded / Rate limited ($statusCode): Please wait a moment before sending more requests.',
          );
        }

        if (statusCode != null && statusCode >= 500) {
          throw Exception(
            '$serviceName is currently unavailable ($statusCode). Please try again shortly.',
          );
        }

        throw Exception(
          apiMessage ??
              'Server returned error ($statusCode): ${error.response?.statusMessage ?? "Unexpected response"}',
        );
      }

      if (error.type == DioExceptionType.cancel) {
        throw Exception('Request was cancelled.');
      }

      throw Exception(
        'Network request failed: ${error.message ?? error.toString()}',
      );
    }

    if (error is SocketException) {
      throw Exception(
        'Network error: Failed to reach $serviceName host. Please check your internet connection.',
      );
    }

    if (error is Exception) {
      throw error;
    }

    throw Exception('$error');
  }
}
